SPRITE_PAL_BASE = 300
COMMON_PAL_AFS = 9
COMMON_PAL_SLOT = 32
STAGE_PAL_SLOT = 300

# Directory containing runtime ColorRAM dump files.
COLORRAM_DUMP_DIR = os.path.join(
    os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
)

# Path to colcd_map.csv (generated by runtime logger in aboutspr.c)
COLCD_MAP_CSV = os.path.join(COLORRAM_DUMP_DIR, "colcd_map.csv")


